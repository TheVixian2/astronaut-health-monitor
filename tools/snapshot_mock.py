"""Record real backend responses into web/mock-snapshot.js for the hosted demo.

GitHub Pages has no backend, so the web app runs in mock mode there. mock.js
simulates the live streams; every other GET it can't simulate is answered from
this snapshot, taken from a real running backend (including the real NASA ISS
cabin reading at the time of the snapshot).

Run with the backend up on :8000, from the repo root:
    backend/.venv/bin/python tools/snapshot_mock.py
"""
import json
import sys
import urllib.request
from pathlib import Path

BASE = sys.argv[1] if len(sys.argv) > 1 else "http://localhost:8000"
CREW = ["a1", "a2", "a3", "a4"]
VIEWERS = ["a1", "ground"]  # Commander page and Mission Control page

paths = ["/habitat", "/environment"]
paths += [f"/crew/locations?viewer={v}" for v in VIEWERS]
paths += [f"/crew/wellbeing?viewer={a}" for a in CREW]
for a in CREW:
    paths.append(f"/astronauts/{a}/vitals")
    paths += [f"/astronauts/{a}/history?hours={h}&bucket_s={b}"
              for h, b in [(24, 3600), (168, 21600), (720, 86400)]]
    paths += [f"/astronauts/{a}/report?days=7&view={v}" for v in ("crew", "ground")]
    paths += [f"/astronauts/{a}/rooms?viewer={v}" for v in VIEWERS]

snap = {}
for p in paths:
    try:
        with urllib.request.urlopen(BASE + p, timeout=15) as r:
            snap[p] = json.load(r)
    except Exception as e:  # a viewer may not be allowed a path; leave it out
        print(f"skip {p}: {e}")

out = Path(__file__).resolve().parent.parent / "web" / "mock-snapshot.js"
out.write_text(
    "// Written with AI assistance (Claude Code, Anthropic) and reviewed by the team. See README \"Use of AI\".\n"
    "// GENERATED by tools/snapshot_mock.py from a real backend run. Do not edit by hand.\n"
    "// Mock mode (GitHub Pages) answers these GETs from here; see mock.js get().\n"
    "window.MOCK_SNAPSHOT = " + json.dumps(snap, separators=(",", ":")) + ";\n",
    encoding="utf-8")
print(f"{len(snap)}/{len(paths)} paths -> {out} ({out.stat().st_size // 1024} KB)")
